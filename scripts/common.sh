# ---- env files ---------------------------------------------------------------
# Main instance: api/.env (hand-edited). Job instance: api/.env.job-<slug>,
# generated with random secrets on first install. Both are git-ignored.
ENV_FILE="${REPO_ROOT}/api/.env${JOB:+.job-${JOB}}"
ENV_EXAMPLE="${REPO_ROOT}/api/.env.example"
API_ENV_FILE="${ENV_FILE}.api"
DB_ENV_FILE="${ENV_FILE}.db"
PMA_ENV_FILE="${ENV_FILE}.pma"
ENV_INSTALL_DIR="${HOME}/.config/bookmark-manager${SUFFIX}"

# ---- output helpers ----------------------------------------------------------
_TAG="$(basename "${0%.sh}")"
if [[ -t 1 ]]; then
  RED='\033[0;31m'; YELLOW='\033[1;33m'; GREEN='\033[0;32m'; CYAN='\033[0;36m'; NC='\033[0m'
else
  RED=''; YELLOW=''; GREEN=''; CYAN=''; NC=''
fi
info()    { echo -e "${CYAN}[${_TAG}]${NC} $*"; }
success() { echo -e "${GREEN}[${_TAG}]${NC} $*"; }
warn()    { echo -e "${YELLOW}[${_TAG}]${NC} $*"; }
error()   { echo -e "${RED}[${_TAG}]${NC} $*" >&2; }

# Read one KEY=value from an env file (quotes stripped).
load_env_value() {
  grep -E "^$2=" "$1" | tail -n1 | cut -d= -f2- | tr -d "'\""
}

# Show which instance a script acts on.
describe_instance() {
  if [[ -n "${JOB}" ]]; then
    info "Instance: ${INSTANCE} (JOB=${JOB}, PORT_OFFSET=${PORT_OFFSET})"
  else
    info "Instance: ${INSTANCE} (main)"
  fi
}

# Wait until GET <url> answers 2xx. Args: url, max seconds.
wait_for_url() {
  local url="$1" max="${2:-60}" elapsed=0
  until curl -sf "${url}" >/dev/null 2>&1; do
    if (( elapsed >= max )); then
      return 1
    fi
    sleep 2
    elapsed=$((elapsed + 2))
  done
}

# Random hex secret without host toolchains.
random_secret() {
  od -An -N"${1:-32}" -tx1 /dev/urandom | tr -d ' \n'
}
