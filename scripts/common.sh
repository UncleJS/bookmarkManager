# shellcheck shell=bash
# =============================================================================
# scripts/common.sh — Shared names, ports and helpers. Sourced, not executed.
#
# Every lifecycle script sources this file. It:
#   - cd's to the repo root, so scripts work from any directory
#   - defines every name the repo creates (pod, units, containers, images,
#     volumes, env dirs) and every published port
#   - supports parallel job instances:
#       JOB=<slug>        suffix every name with -<slug>
#       PORT_OFFSET=<n>   add <n> to every published port (default 0)
#     e.g. JOB=bm-infra PORT_OFFSET=2000 → pod bookmark-bm-infra on 13650/13651
#   - labels everything with app=bookmark-manager and
#     bookmark-manager.instance=<instance> so uninstall.sh can find it
# =============================================================================

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

# ---- instance ----------------------------------------------------------------
JOB="${JOB:-}"
if [[ -n "${JOB}" && ! "${JOB}" =~ ^[a-z0-9][a-z0-9-]*$ ]]; then
  echo "JOB must be lowercase letters, digits and dashes (got '${JOB}')." >&2
  exit 2
fi
SUFFIX="${JOB:+-${JOB}}"
INSTANCE="bookmark${SUFFIX}"

# PORT_OFFSET: from the environment; if unset, read back from the installed
# pod unit of this instance (so later start/rebuild calls use the right port);
# otherwise 0.
PORT_OFFSET_SET=0
if [[ -n "${PORT_OFFSET:-}" ]]; then
  PORT_OFFSET_SET=1
else
  _pod_unit="${HOME}/.config/containers/systemd/bookmark${SUFFIX}.pod"
  _host_port="$(sed -n 's/^PublishPort=127\.0\.0\.1:\([0-9]*\):11650$/\1/p' "${_pod_unit}" 2>/dev/null | head -n1 || true)"
  PORT_OFFSET=$(( ${_host_port:-11650} - 11650 ))
fi
if [[ ! "${PORT_OFFSET}" =~ ^[0-9]+$ ]]; then
  echo "PORT_OFFSET must be a non-negative integer (got '${PORT_OFFSET}')." >&2
  exit 2
fi
PORT_OFFSET=$((10#${PORT_OFFSET}))
if (( 11651 + PORT_OFFSET > 65535 )); then
  echo "PORT_OFFSET ${PORT_OFFSET} pushes the ports above 65535." >&2
  exit 2
fi

# ---- labels ------------------------------------------------------------------
APP_LABEL="app=bookmark-manager"
INSTANCE_LABEL="bookmark-manager.instance=${INSTANCE}"

# ---- ports (host side; container ports never change) -------------------------
API_CONTAINER_PORT=11650
PMA_CONTAINER_PORT=80
API_HOST_PORT=$((11650 + PORT_OFFSET))
PMA_HOST_PORT=$((11651 + PORT_OFFSET))
API_URL="http://localhost:${API_HOST_PORT}"
PMA_URL="http://localhost:${PMA_HOST_PORT}"

# ---- Quadlet unit files (repo source → installed name) ----------------------
QUADLET_SRC="${REPO_ROOT}/quadlet"
QUADLET_DEST="${HOME}/.config/containers/systemd"
# Source file names in quadlet/; installed as <base>${SUFFIX}.<ext>
QUADLET_FILES=(bookmark.pod bookmark-db.volume bookmark-db.container bookmark-api.container bookmark-pma.container)
installed_unit_name() { # bookmark-db.container → bookmark-db-<job>.container
  local f="$1"
  echo "${f%.*}${SUFFIX}.${f##*.}"
}

