POD_SERVICE="bookmark${SUFFIX}-pod.service"
API_SERVICE="bookmark-api${SUFFIX}.service"
DB_SERVICE="bookmark-db${SUFFIX}.service"
PMA_SERVICE="bookmark-pma${SUFFIX}.service"
VOLUME_SERVICE="bookmark-db${SUFFIX}-volume.service"
ALL_SERVICES=("${POD_SERVICE}" "${DB_SERVICE}" "${API_SERVICE}" "${PMA_SERVICE}" "${VOLUME_SERVICE}")

# ---- Podman objects ----------------------------------------------------------
POD_NAME="systemd-bookmark${SUFFIX}"   # Quadlet's default pod name for bookmark${SUFFIX}.pod
API_CONTAINER="bookmark-api${SUFFIX}"
DB_CONTAINER="bookmark-db${SUFFIX}"
PMA_CONTAINER="bookmark-pma${SUFFIX}"
DB_VOLUME="bookmark-db-data${SUFFIX}"

API_IMAGE="localhost/bookmark-api${SUFFIX}:latest"          # used by the installed unit
